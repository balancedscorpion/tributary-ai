package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"ai-analyst-local/internal/chat/tools"
)

func main() {
	outPath := flag.String("out", "", "path to write generated TypeScript metadata")
	flag.Parse()

	var metadataPayload bytes.Buffer
	metadataEncoder := json.NewEncoder(&metadataPayload)
	metadataEncoder.SetEscapeHTML(false)
	metadataEncoder.SetIndent("", "  ")
	if err := metadataEncoder.Encode(tools.AllToolMetadata()); err != nil {
		fail("encode tool metadata: %v", err)
	}

	var providerHostedPayload bytes.Buffer
	providerHostedEncoder := json.NewEncoder(&providerHostedPayload)
	providerHostedEncoder.SetEscapeHTML(false)
	providerHostedEncoder.SetIndent("", "  ")
	if err := providerHostedEncoder.Encode(tools.ProviderHostedToolCapabilities()); err != nil {
		fail("encode provider-hosted tool capabilities: %v", err)
	}

	content := fmt.Sprintf(`// Code generated by server/cmd/toolinventorygen; DO NOT EDIT.
// Regenerate with: (cd server && go generate ./internal/chat/tools)

export const GENERATED_STATIC_TOOL_METADATA = %s as const;

export const GENERATED_STATIC_PROVIDER_HOSTED_TOOL_CAPABILITIES = %s as const;
`, strings.TrimRight(metadataPayload.String(), "\n"), strings.TrimRight(providerHostedPayload.String(), "\n"))

	if strings.TrimSpace(*outPath) == "" {
		fmt.Print(content)
		return
	}
	if err := os.MkdirAll(filepath.Dir(*outPath), 0o755); err != nil {
		fail("create output directory: %v", err)
	}
	if err := os.WriteFile(*outPath, []byte(content), 0o644); err != nil {
		fail("write %s: %v", *outPath, err)
	}
}

func fail(format string, args ...any) {
	fmt.Fprintf(os.Stderr, format+"\n", args...)
	os.Exit(1)
}
